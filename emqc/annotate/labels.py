"""平台保留的标签 id——目前只有一个：「细胞间隙」。

分割里的 0 是「还没人标」，不是「这里没有细胞」。标注员看过一块地方、确认它确实是细胞之间的空隙之后，
需要一个办法把这个判断记下来，否则这块地方永远像是漏标的。「细胞间隙」就是这个记号：一个全平台通用、
在每个数据块里都一样的固定 id，一键可用。

为什么是 2**63：H01 的细胞 id 在 1e9 ~ 2e10 这个量级，平台新建的 id 是「当前最大 + 1」，都远低于这个数；
它又比 uint64 的上限小得多，「最大 + 1」永远不会碰到它。它也不能是个小数字——别的数据集（鼠脑）的 id
可能从 1 开始编。

写它的规矩只有一条，在 store.py 里逐个操作落实：**细胞间隙只能落在 id 为 0 的像素上，永远不盖掉任何细胞。**
反过来不限制——一块先标成间隙的地方，后来发现其实是某个细胞，照常用那个细胞的颜色盖上去就行。
"""
GAP_ID = 2 ** 63                     # 9223372036854775808
GAP_NAME = "细胞间隙"
GAP_COLOR = (148, 163, 184)          # 低饱和的灰蓝：一眼看出「不是细胞」，又不会和透明的未标注区混在一起
